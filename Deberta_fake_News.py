train_df = pd.read_csv(train_path)

# -----------------------------
# Step 2: Preprocess Data
# -----------------------------
train_df['title'] = train_df['title'].fillna("")
train_df['text'] = train_df['text'].fillna("")
train_df['author'] = train_df['author'].fillna("")  # Include author column

# Combine all textual features
train_df['combined_text'] = train_df['author'] + " " + train_df['title'] + " " + train_df['text']

# Tokenization parameters
max_len = 128
vocab_size = 10000
embedding_dim = 128

# Initialize and fit the Keras Tokenizer
tokenizer = Tokenizer(num_words=vocab_size)
tokenizer.fit_on_texts(train_df['combined_text'])
X_train_seq = tokenizer.texts_to_sequences(train_df['combined_text'])
X_train_pad = pad_sequences(X_train_seq, maxlen=max_len, dtype='int32')

# -----------------------------
# Step 3: Load Pretrained DeBERTa Model
# -----------------------------
print("Loading DeBERTa model...")
transformer = TFAutoModel.from_pretrained("microsoft/deberta-v3-small")

def extract_embeddings(model, input_ids, batch_size=16):
    all_embeddings = []
    for i in range(0, input_ids.shape[0], batch_size):
        batch_input_ids = tf.convert_to_tensor(input_ids[i:i+batch_size])
        # Use the [CLS] token embedding (index 0)
        batch_embeddings = model(batch_input_ids).last_hidden_state[:, 0, :]
        all_embeddings.append(batch_embeddings.numpy())
    return np.concatenate(all_embeddings, axis=0)

# Extract transformer embeddings (shape: (num_samples, 768))
X_train_bert = extract_embeddings(transformer, X_train_pad, batch_size=16)
print("Shape of DeBERTa embeddings:", X_train_bert.shape)

# -----------------------------
# Step 4: Define CNN Model for Feature Extraction
# -----------------------------
# CNN architecture definition
def create_embedding_cnn():
    input_tensor = Input(shape=(max_len,))
    x = Embedding(vocab_size, embedding_dim, input_length=max_len)(input_tensor)
    x = Conv1D(128, 5, activation='relu')(x)
    x = GlobalMaxPooling1D()(x)
    return Model(input_tensor, x)

cnn_model = create_embedding_cnn()

# Make sure you run predict once to initialize the layers
X_train_cnn = cnn_model.predict(X_train_pad)

# Explicitly build CNN model before saving weights
cnn_model.build(input_shape=(None, max_len))

# Now correctly save CNN weights
cnn_model.save_weights("/content/drive/My Drive/fakenews/embedding_cnn_model.weights.h5")
print("✅ CNN Embedding model weights saved correctly!")


embedding_cnn_model = create_embedding_cnn()
X_train_cnn = embedding_cnn_model.predict(X_train_pad)
print("Shape of CNN features:", X_train_cnn.shape)

# -----------------------------
# Step 5: Combine Features
# -----------------------------
# Combined features: transformer embeddings (768-dim) + CNN features (128-dim) = 896-dim vector.
X_train_features = np.concatenate([X_train_bert, X_train_cnn], axis=1)
print("Shape of combined features:", X_train_features.shape)

# -----------------------------
# Step 6: Define Discriminator Model
# -----------------------------
class Discriminator(Model):
    def __init__(self):
        super(Discriminator, self).__init__()
        self.dense1 = Dense(512, activation='relu')
        self.batch_norm1 = BatchNormalization()
        self.dense2 = Dense(256, activation='relu')
        self.batch_norm2 = BatchNormalization()
        self.dropout1 = Dropout(0.3)
        self.dense3 = Dense(128, activation='relu')
        self.batch_norm3 = BatchNormalization()
        self.dense4 = Dense(1, activation='sigmoid')

    def call(self, inputs):
        x = self.dense1(inputs)
        x = self.batch_norm1(x)
        x = self.dense2(x)
        x = self.batch_norm2(x)
        x = self.dropout1(x)
        x = self.dense3(x)
        x = self.batch_norm3(x)
        return self.dense4(x)

# -----------------------------
# Optimized Learning Rate Strategy
# -----------------------------
initial_learning_rate = 5e-4
lr_schedule = tf.keras.optimizers.schedules.ExponentialDecay(
    initial_learning_rate,
    decay_steps=1000,
    decay_rate=0.96,
    staircase=True
)
optimizer = Adam(learning_rate=lr_schedule)

discriminator = Discriminator()
discriminator.compile(
    optimizer=optimizer,
    loss='binary_crossentropy',
    metrics=['accuracy']
)

# -----------------------------
# Step 7: Train Model
# -----------------------------
y_train = train_df['label'].values
discriminator.fit(X_train_features, y_train, validation_split=0.2, epochs=200, batch_size=128)

# -----------------------------
# Step 8: Evaluate Model
# -----------------------------
y_train_pred_prob = discriminator.predict(X_train_features)
y_train_pred = (y_train_pred_prob > 0.45).astype(int)

accuracy = accuracy_score(y_train, y_train_pred)
precision = precision_score(y_train, y_train_pred)
recall = recall_score(y_train, y_train_pred)
f1 = f1_score(y_train, y_train_pred)

print(f"Accuracy: {accuracy:.4f}")
print(f"Precision: {precision:.4f}")
print(f"Recall: {recall:.4f}")
print(f"F1-Score: {f1:.4f}")
print("\nClassification Report:\n", classification_report(y_train, y_train_pred))

cm = confusion_matrix(y_train, y_train_pred)
plt.figure(figsize=(6,5))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=['Real', 'Fake'], yticklabels=['Real', 'Fake'])
plt.xlabel('Predicted Label')
plt.ylabel('True Label')
