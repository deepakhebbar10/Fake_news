# 3. TOKENIZATION (RETURNS TF TENSORS)
encoded_inputs = tokenizer(
    list(train_df['combined_text']),
    return_tensors="tf",   # Return TensorFlow Tensors
    padding=True,
    truncation=True,
    max_length=128
)
X_input_ids = encoded_inputs["input_ids"]            # shape: (num_samples, 128)
X_attention_masks = encoded_inputs["attention_mask"] # shape: (num_samples, 128)

# 4. CREATE A CUSTOM WRAPPER LAYER FOR DEBERTA
class DebertaLayer(Layer):
    def __init__(self, model_name, **kwargs):
        super().__init__(**kwargs)
        self.transformer = TFAutoModel.from_pretrained(model_name)
        # Unfreeze all layers for fine-tuning
        for layer in self.transformer.layers:
            layer.trainable = True

    def call(self, inputs, training=False):
        input_ids, attention_mask = inputs
        outputs = self.transformer(
            input_ids=input_ids,
            attention_mask=attention_mask,
            training=training
        )
        # outputs.last_hidden_state => (batch_size, seq_len, hidden_dim)
        return outputs.last_hidden_state

# 5. BUILD THE MODEL WITH KERAS FUNCTIONAL API
#    a) Keras Input layers
input_ids_layer = Input(shape=(128,), dtype=tf.int32, name="input_ids")
attention_mask_layer = Input(shape=(128,), dtype=tf.int32, name="attention_mask")

#    b) Pass inputs through custom DeBERTa wrapper
deberta_layer = DebertaLayer(model_name=model_name)
hidden_states = deberta_layer([input_ids_layer, attention_mask_layer])
# shape: (batch_size, seq_len, hidden_dim)

#    c) Mean Pooling via Lambda Layer
mean_pool_layer = Lambda(lambda x: tf.reduce_mean(x, axis=1), name="mean_pool")
mean_pooled = mean_pool_layer(hidden_states)  # shape: (batch_size, hidden_dim)

#    d) Classification Head
x = Dense(512, activation='relu')(mean_pooled)
x = BatchNormalization()(x)
x = Dropout(0.3)(x)

x = Dense(256, activation='relu')(x)
x = BatchNormalization()(x)
x = Dropout(0.3)(x)

x = Dense(128, activation='relu')(x)
x = BatchNormalization()(x)

output = Dense(1, activation='sigmoid')(x)

model = Model(inputs=[input_ids_layer, attention_mask_layer], outputs=output)

# 6. COMPILE & TRAIN
optimizer = Adam(learning_rate=1e-5)  # typical LR for Transformer fine-tuning
model.compile(
    optimizer=optimizer,
    loss='binary_crossentropy',
    metrics=['accuracy']
)


